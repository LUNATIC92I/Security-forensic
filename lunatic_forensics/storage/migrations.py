"""Minimal versioned schema migrations.

Each migration is a function receiving a SQLAlchemy connection. The applied
version is stored in ``schema_version``. New migrations must be appended to
``MIGRATIONS`` and never modified once released. The approach works with
SQLite and PostgreSQL; Alembic can replace it when a server deployment needs
autogenerated migrations.
"""
from __future__ import annotations

from sqlalchemy import Engine, text

from . import models


def _m001_initial(conn) -> None:
    models.Base.metadata.create_all(conn)


def _m002_audit_indexes(conn) -> None:
    conn.execute(text("CREATE INDEX IF NOT EXISTS ix_audit_ts ON audit_log (timestamp)"))
    conn.execute(text("CREATE INDEX IF NOT EXISTS ix_art_ident ON artifacts (case_id, identifiers)"))


MIGRATIONS = [
    (1, "initial schema", _m001_initial),
    (2, "audit and identifier indexes", _m002_audit_indexes),
]

LATEST = MIGRATIONS[-1][0]


def current_version(engine: Engine) -> int:
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL, description TEXT, applied_at TEXT DEFAULT CURRENT_TIMESTAMP)"))
        row = conn.execute(text("SELECT MAX(version) FROM schema_version")).scalar()
        return int(row or 0)


def migrate(engine: Engine) -> int:
    version = current_version(engine)
    for num, desc, fn in MIGRATIONS:
        if num > version:
            with engine.begin() as conn:
                fn(conn)
                conn.execute(text("INSERT INTO schema_version (version, description) VALUES (:v, :d)"), {"v": num, "d": desc})
            version = num
    return version
